function archivedIds(existingIds, submittedIds) {
  const submitted = new Set(submittedIds);
  return existingIds.filter((id) => !submitted.has(id));
}

function validateMoney(currency, major, minor) {
  if (!Number.isSafeInteger(minor) || minor < 0) return false;
  if (currency === "INR") return Number.isFinite(major) && major >= 0 && minor === major * 100;
  if (currency === "USD") return major != null && Number.isFinite(major) && major >= 0;
  return false;
}

function countToken(source, token) {
  return source.split(token).length - 1;
}

