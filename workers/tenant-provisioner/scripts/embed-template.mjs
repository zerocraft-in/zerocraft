#!/usr/bin/env node
/**
 * Embeds the commerce template SQL into the Worker bundle.
 *
 * Workers cannot read repository files at runtime, and deploy artifacts must be
 * immutable. This script produces src/template-bundle.ts from
 * templates/commerce/template.config.json plus the referenced files.
 *
 * Run after any template change:
 *   node workers/tenant-provisioner/scripts/embed-template.mjs
 */

import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const repoRoot = resolve(import.meta.dirname, "../../..");
const templateRoot = resolve(repoRoot, "templates/commerce");
const config = JSON.parse(readFileSync(resolve(templateRoot, "template.config.json"), "utf8"));

function load(entries) {
  return entries.map((entry) => ({
    version: entry.version,
    kind: entry.kind,
    file: entry.file,
    checksum: entry.checksum,
    sql: readFileSync(resolve(templateRoot, entry.file), "utf8")
  }));
}

const verification = load(config.verification).sort((a, b) => {
  const rank = (file) =>
    file.includes("schema-verification") ? 0 : file.includes("rls-verification") ? 1 : 2;
  return rank(a.file) - rank(b.file);
});

const bundle = {
  name: config.name,
  version: config.version,
  protectedProjects: config.protectedProjects,
  migrations: load(config.migrations),
  seeds: load(config.seeds),
  verification
};

const header = `// AUTO-GENERATED by scripts/embed-template.mjs — do not edit.
// Source: templates/commerce/ (version ${bundle.version})
`;

const body = `export interface TemplateFile {
  version: string;
  kind: "migration" | "seed" | "verify";
  file: string;
  checksum: string;
  sql: string;
}

export interface TemplateBundle {
  name: string;
  version: string;
  protectedProjects: string[];
  migrations: TemplateFile[];
  seeds: TemplateFile[];
  verification: TemplateFile[];
}

export const TEMPLATE_BUNDLE: TemplateBundle = ${JSON.stringify(bundle, null, 2)};
`;

const target = resolve(import.meta.dirname, "../src/template-bundle.ts");
writeFileSync(target, header + body, "utf8");

console.log(
  `embedded ${bundle.migrations.length} migrations, ${bundle.seeds.length} seeds, ` +
    `${bundle.verification.length} verification files (template ${bundle.version})`
);
